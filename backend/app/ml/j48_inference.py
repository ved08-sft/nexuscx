def _heuristic_escalation_probability(features: Dict[str, Any]) -> float:
    """
    Simple heuristic for escalation probability when no model is available.
    Based on the risk factors mentioned in the requirements.
    """
    # Extract features with defaults
    handle_time = float(features.get("avg_handling_time_sec", 0))
    past_escalation = float(features.get("past_escalation_count", 0))
    sentiment = float(features.get("customer_sentiment_score", 0.0))
    channel_type = features.get("channel_type", "voice")
    ekyc_verified = str(features.get("ekyc_verified", False)).lower() == "true"

    # Start with base probability
    probability = 0.1

    # Handle time factor (longer calls more likely to escalate)
    if handle_time > 600:  # > 10 minutes
        probability += 0.2
    elif handle_time > 300:  # > 5 minutes
        probability += 0.1

    # Past escalation factor
    probability += min(0.3, past_escalation * 0.05)  # Up to 0.3

    # Sentiment factor (more negative = higher escalation risk)
    if sentiment < -0.5:
        probability += 0.3
    elif sentiment < -0.2:
        probability += 0.2
    elif sentiment < 0:
        probability += 0.1

    # Channel factor
    if channel_type == "email":
        probability += 0.1  # Email might have more complex issues
    elif channel_type == "chat":
        probability += 0.05

    # eKYC verification factor (unverified might increase risk)
    if not ekyc_verified:
        probability += 0.1

    # Vertical factor (handled elsewhere, but keeping for completeness)
    # vertical = features.get("vertical", "billing")
    # if vertical in ["flight", "technical"]:
    #     probability += 0.05

    # Clamp to valid probability range
    return max(0.0, min(1.0, probability))


def _heuristic_churn_risk_class(features: Dict[str, Any]) -> str:
    """
    Simple heuristic for churn risk class when no model is available.
    """
    # Extract features with defaults
    handle_time = float(features.get("avg_handling_time_sec", 0))
    past_escalation = float(features.get("past_escalation_count", 0))
    sentiment = float(features.get("customer_sentiment_score", 0.0))
    # Note: churn model uses different features than escalation model
    # But for this fallback, we'll use similar logic

    # Simple scoring system
    score = 0

    # Handle time factor
    if handle_time > 600:
        score += 2
    elif handle_time > 300:
        score += 1

    # Past escalation factor
    score += min(3, int(past_escalation))

    # Sentiment factor (more negative = higher churn risk)
    if sentiment < -0.5:
        score += 2
    elif sentiment < -0.2:
        score += 1

    # Map score to risk class
    if score >= 4:
        return "HIGH"
    elif score >= 2:
        return "MEDIUM"
    else:
        return "LOW"


